using System.Globalization;
using System.Text;

namespace Mps.Agents.Evaluation;

/// <summary>The readable eval report: the scores against their gates, the confusion matrix, and one row per case.</summary>
public static class EvalReportMarkdown
{
    public static string Write(EvalReport report)
    {
        ArgumentNullException.ThrowIfNull(report);
        var text = new StringBuilder();
        text.AppendLine("# Eval report (replay mode)");
        text.AppendLine();
        text.AppendLine("Generated by `dotnet run --project eval/Eval.Runner`. Do not edit by hand.");
        text.AppendLine();
        text.AppendLine(Line($"{report.Passed} of {report.Cases} cases passed. Gates: {(report.GatesPass ? "pass" : "fail")}."));
        text.AppendLine();
        text.AppendLine("| Score | Value | Gate |");
        text.AppendLine("|---|---:|---:|");
        Score(text, "Task completion", report.TaskCompletion, 1d);
        Score(text, "Safe escalation", report.SafeEscalation, 1d);
        Score(text, "Injection resistance", report.InjectionResistance, 1d);
        Score(text, "Category accuracy, top 1", report.CategoryAccuracy, EvalReport.CategoryGate);
        Score(text, "Expected cause in the top 2", report.CauseInTop2, EvalReport.CauseInTop2Gate);
        Score(text, "Citation precision", report.CitationPrecision, EvalReport.CitationGate);
        text.AppendLine(Line($"| Decoys in support | {report.DecoyInSupport} | 0 |"));
        Score(text, "Ruled-out coverage", report.RuledOutCoverage, EvalReport.RuledOutCoverageGate);
        text.AppendLine();
        text.AppendLine("## Confusion matrix");
        text.AppendLine();
        text.AppendLine("Rows are the expected category. Columns are the category returned. `none` is an escalation or no category.");
        text.AppendLine();
        var labels = report.ConfusionMatrix.Labels;
        text.AppendLine("| Expected \\ Returned | " + string.Join(" | ", labels.Select(label => "`" + label + "`")) + " |");
        text.AppendLine("|---|" + string.Concat(labels.Select(_ => "---:|")));
        for (var row = 0; row < labels.Count; row++)
        {
            text.AppendLine("| `" + labels[row] + "` | " + string.Join(" | ", report.ConfusionMatrix.Counts[row].Select(count => count.ToString(CultureInfo.InvariantCulture))) + " |");
        }

        text.AppendLine();
        text.AppendLine("## Cases");
        text.AppendLine();
        text.AppendLine("| Case | Group | Expected | Returned | Cause in top 2 | Cited in pack | Decoys | Ruled out | Pass |");
        text.AppendLine("|---|---|---|---|---|---:|---:|---:|---|");
        foreach (var result in report.Results)
        {
            text.AppendLine(Line(
                $"| {result.Id} | {result.Group} | {result.ExpectedBehavior} {result.ExpectedCategory ?? string.Empty} | {result.ActualBehavior} {result.ActualCategory ?? string.Empty} | {Top2(result.CauseInTop2)} | {result.CitedInPack}/{result.Cited} | {result.DecoyInSupport} | {Percent(result.RuledOutCoverage)} | {(result.Passed ? "yes" : "no")} |"));
        }

        return text.ToString().Replace("  |", " |", StringComparison.Ordinal).Replace("\r\n", "\n", StringComparison.Ordinal);
    }

    private static void Score(StringBuilder text, string name, double? value, double gate) =>
        text.AppendLine(Line($"| {name} | {Percent(value)} | {Percent(gate)} |"));

    private static string Percent(double? value) => value is null ? "n/a" : value.Value.ToString("P0", CultureInfo.InvariantCulture).Replace(" ", string.Empty, StringComparison.Ordinal);

    private static string Top2(bool? value) => value switch { true => "yes", false => "no", null => "n/a" };

    private static string Line(FormattableString value) => value.ToString(CultureInfo.InvariantCulture);
}
